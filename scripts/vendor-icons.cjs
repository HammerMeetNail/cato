#!/usr/bin/env node
// Generates web/static/js/ui/icons.js from Lucide's icon-nodes.json and
// scripts/icon-list.txt. Run by scripts/vendor-update.sh; the output is
// checked in (no build step at runtime).
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const [nodesFile, outFile] = process.argv.slice(2);
if (!nodesFile || !outFile) {
  console.error('usage: vendor-icons.cjs icon-nodes.json web/static/js/ui/icons.js');
  process.exit(2);
}
const nodes = JSON.parse(fs.readFileSync(nodesFile, 'utf8'));
const names = fs.readFileSync(path.join(__dirname, 'icon-list.txt'), 'utf8')
  .split('\n').map(s => s.trim()).filter(s => s && !s.startsWith('#'));
const out = {};
for (const name of names) {
  if (!nodes[name]) { console.error(`unknown icon ${name}`); process.exit(1); }
  out[name] = nodes[name];
}
const header = `// Generated by scripts/vendor-icons.cjs from lucide-static (ISC licence,
// js/vendor/LUCIDE-LICENSE). Do not edit; add names to scripts/icon-list.txt.
`;
fs.writeFileSync(outFile, header + 'export const iconNodes = ' + JSON.stringify(out) + ';\n');
console.log(`${names.length} icons -> ${outFile}`);
